#!/usr/bin/env bash
#
# Adds, or updates, what the Linked Data Explorer and the ttl-editor need in
# the ronl realm to sign people in (linked-data-explorer #163): the realm role
# lde-author, which the LDE backend requires on every state-changing call, and
# the public clients linked-data-explorer and ttl-editor. With --with-e2e it
# also adds the confidential client lde-e2e and the user lde-e2e, whose token
# the e2e fixtures deploy uses.
# Design: linked-data-explorer docs/superpowers/specs/2026-11-09-backend-write-auth-design.md
#
# WHY NOT A REALM IMPORT
# ----------------------
# Same reason as keycloak-add-rip-roles.sh and keycloak-add-entra-idp.sh:
# partial import either skips what exists or overwrites whole definitions an
# environment configured by hand. config/keycloak/ronl-realm.json is not
# changed, so a fresh local --import-realm has none of this, and this script
# is run again after it.
#
# WHAT IT SENDS
# -------------
# Everything is defined in keycloak-lde-clients.json. The script fills in the
# origins: redirect URIs "<origin>/*", web origin "<origin>", and post-logout
# redirect "<origin>/*". Each client carries its own realm_roles, username and
# full name mappers, as ronl-business-api does, so its tokens hold
# realm_access.roles, preferred_username and name whatever the realm's default
# client scopes are. A role, client, mapper or user that exists is updated in
# place, never duplicated, so the script is safe to re-run. A mapper someone
# added by hand is left alone.
#
# THE E2E ACCOUNT
# ---------------
# --with-e2e is refused against production (keycloak.open-regels.nl). The
# user's password is read from LDE_E2E_PASSWORD (prompted when unset); it
# reaches jq through the environment, never argv, and --dry-run shows it as
# "<redacted>". The lde-e2e client secret is generated by Keycloak, kept on
# re-runs, and printed at the end: the only output that contains a secret.
# Put it in LDE_E2E_CLIENT_SECRET where the fixtures deploy runs.
#
#   KEYCLOAK_URL      e.g. https://acc.keycloak.open-regels.nl   (required)
#   REALM             default: ronl
#   ADMIN_USER        default: admin
#   ADMIN_REALM       default: master   (realm the ADMIN account lives in)
#   ADMIN_PASSWORD    required (prompted if unset; not needed for --dry-run)
#   LDE_ORIGIN        required, exact origin, e.g. http://localhost:3000
#   TTL_ORIGIN        required, exact origin, e.g. http://localhost:3002
#   LDE_E2E_PASSWORD  with --with-e2e (prompted if unset; not needed for --dry-run)
#   CLIENTS_FILE      default: scripts/keycloak-lde-clients.json
#
# Usage:
#   KEYCLOAK_URL=http://localhost:8080 \
#   LDE_ORIGIN=http://localhost:3000 TTL_ORIGIN=http://localhost:3002 \
#     bash scripts/keycloak-add-lde-clients.sh [--with-e2e] [--dry-run]
set -euo pipefail

KEYCLOAK_URL="${KEYCLOAK_URL:?set KEYCLOAK_URL, e.g. https://acc.keycloak.open-regels.nl}"
# A trailing slash yields "https://host//realms/..." which some deployments
# reject outright; strip it rather than rely on the server being tolerant.
KEYCLOAK_URL="${KEYCLOAK_URL%/}"
REALM="${REALM:-ronl}"
ADMIN_USER="${ADMIN_USER:-admin}"
ADMIN_REALM="${ADMIN_REALM:-master}"
CLIENTS_FILE="${CLIENTS_FILE:-$(dirname "$0")/keycloak-lde-clients.json}"

DRY_RUN=false
WITH_E2E=false
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=true ;;
    --with-e2e) WITH_E2E=true ;;
    -h|--help) sed -n '2,52p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $arg" >&2; exit 2 ;;
  esac
done

[[ -f "$CLIENTS_FILE" ]] || { echo "missing $CLIENTS_FILE" >&2; exit 1; }
command -v jq >/dev/null || { echo "jq is required" >&2; exit 1; }

# jq on Windows is a native binary writing in text mode: every line it emits
# ends CRLF, so a value read straight into a shell variable carries a trailing
# carriage return. Strip it wherever a jq value lands in a variable.
jqr() { jq "$@" | tr -d '\r'; }

# The e2e account is a password-grant account with write access to the shared
# library. Production has no use for it, so it never gets one.
if [[ "$WITH_E2E" == "true" && "$KEYCLOAK_URL" =~ ^https?://keycloak\.open-regels\.nl(:443)?$ ]]; then
  echo "--with-e2e is refused on production (${KEYCLOAK_URL}): no e2e account there" >&2
  exit 2
fi

# An origin is scheme://host[:port] and nothing else. A path or a trailing
# slash would make "<origin>/*" and the web origin silently wrong, and the
# sign-in would fail at Keycloak with "Invalid redirect uri".
ORIGIN_RE='^https?://[^/[:space:]]+$'
check_origin() {
  local name="$1" value="${!1:-}"
  value="${value//$'\r'/}"
  [[ -n "$value" ]] || { echo "set ${name}, e.g. http://localhost:3000" >&2; exit 2; }
  [[ "$value" =~ $ORIGIN_RE ]] || { echo "${name} is not an origin (scheme://host[:port], no path): '${value}'" >&2; exit 2; }
  printf -v "$name" '%s' "$value"
  export "${name?}"
}
while IFS= read -r var; do check_origin "$var"; done < <(jqr -r '.publicClients[].originVar' "$CLIENTS_FILE")

ROLE_NAME=$(jqr -r '.role.name' "$CLIENTS_FILE")
E2E_CLIENT=$(jqr -r '.e2eClient.clientId' "$CLIENTS_FILE")
E2E_USER=$(jqr -r '.e2eUser.username' "$CLIENTS_FILE")
PUBLIC_COUNT=$(jqr '.publicClients | length' "$CLIENTS_FILE")

# The public client representation for entry $1, with its origin filled in.
public_client_json() {
  jq -c --argjson i "$1" '
    .publicClients[$i] as $c
    | ($ENV[$c.originVar]) as $o
    | .publicClientDefaults + {
        clientId: $c.clientId, name: $c.name, description: $c.description,
        rootUrl: $o, baseUrl: "/",
        redirectUris: [($o + "/*")], webOrigins: [$o]
      }
    | .attributes += { "post.logout.redirect.uris": ($o + "/*") }' "$CLIENTS_FILE"
}
e2e_client_json() { jq -c '.e2eClient' "$CLIENTS_FILE"; }
e2e_user_json() { jq -c '.e2eUser' "$CLIENTS_FILE"; }
password_json() { jq -nc '{type: "password", temporary: false, value: $ENV.LDE_E2E_PASSWORD}'; }

if [[ "$DRY_RUN" == "true" ]]; then
  echo "→ dry run: nothing is sent to ${KEYCLOAK_URL}"
  echo "→ realm role in ${REALM}:"
  jq '.role' "$CLIENTS_FILE"
  for ((i = 0; i < PUBLIC_COUNT; i++)); do
    echo "→ public client:"
    public_client_json "$i" | jq .
  done
  echo "→ mappers on every client:"
  jqr -r '.mappers[] | "  \(.name)  \(.protocolMapper)  \(.config["claim.name"] // "")"' "$CLIENTS_FILE"
  if [[ "$WITH_E2E" == "true" ]]; then
    echo "→ confidential client (secret generated by Keycloak):"
    e2e_client_json | jq .
    echo "→ user, granted ${ROLE_NAME}:"
    e2e_user_json | jq .
    export LDE_E2E_PASSWORD="<redacted>"
    echo "→ password:"
    password_json | jq .
  fi
  exit 0
fi

if [[ "$WITH_E2E" == "true" ]]; then
  if [[ -z "${LDE_E2E_PASSWORD:-}" ]]; then
    read -rsp "Password for the ${E2E_USER} user: " LDE_E2E_PASSWORD
    echo
  fi
  LDE_E2E_PASSWORD="${LDE_E2E_PASSWORD//$'\r'/}"
  [[ -n "$LDE_E2E_PASSWORD" ]] || { echo "LDE_E2E_PASSWORD is empty" >&2; exit 2; }
  export LDE_E2E_PASSWORD
fi

if [[ -z "${ADMIN_PASSWORD:-}" ]]; then
  read -rsp "Keycloak admin password for ${ADMIN_USER}@${KEYCLOAK_URL}: " ADMIN_PASSWORD
  echo
fi

# Responses and the bearer token live in a private directory, removed however
# the script ends (#252).
TMPD=$(mktemp -d)
trap 'rm -rf "$TMPD"' EXIT

# ── Admin token ──────────────────────────────────────────────────────────────
TOKEN_URL="${KEYCLOAK_URL}/realms/${ADMIN_REALM}/protocol/openid-connect/token"
echo "→ authenticating as ${ADMIN_USER} against realm ${ADMIN_REALM}"
# The password goes in on stdin, never as an argument, so it is not in the
# process list while curl runs (#252).
TOKEN_CODE=$(printf '%s' "$ADMIN_PASSWORD" | curl -sS -o "$TMPD/token.out" -w '%{http_code}' \
  -X POST "$TOKEN_URL" \
  -d "client_id=admin-cli" -d "grant_type=password" \
  --data-urlencode "username=${ADMIN_USER}" \
  --data-urlencode "password@-" || true)
TOKEN=$(jqr -r '.access_token // empty' "$TMPD/token.out" 2>/dev/null || true)

if [[ -z "$TOKEN" ]]; then
  {
    echo "could not obtain an admin token (HTTP ${TOKEN_CODE})"
    echo "  POST ${TOKEN_URL}"
    echo
    echo "  401 invalid_grant      -> wrong username/password"
    echo "  404 / realm not found  -> the admin is not in '${ADMIN_REALM}'; try ADMIN_REALM=${REALM}"
    echo "  HTML instead of JSON   -> the URL is not hitting Keycloak directly (proxy/ingress)"
  } >&2
  exit 1
fi
# The header reaches curl through a 0600 config file, not argv (#252).
printf 'header = "Authorization: Bearer %s"\n' "$TOKEN" >"$TMPD/auth.cfg"
chmod 600 "$TMPD/auth.cfg"
AUTH=(-K "$TMPD/auth.cfg")
BASE="${KEYCLOAK_URL}/admin/realms/${REALM}"

REALM_CODE=$(curl -sS -o /dev/null -w '%{http_code}' "${AUTH[@]}" "$BASE")
[[ "$REALM_CODE" == "200" ]] || {
  echo "realm '${REALM}' not reachable (HTTP ${REALM_CODE}) — check REALM and admin rights" >&2
  exit 1
}

# report <what> <expected code> <actual code> <verb>: prints the outcome, exits on failure.
report() {
  local what="$1" want="$2" got="$3" verb="$4"
  if [[ "$got" == "$want" ]]; then
    printf '  %-13s %s\n' "$verb" "$what"
  else
    echo "  FAILED        ${what} -> HTTP ${got}: $(head -c 200 "$TMPD/out")" >&2
    exit 1
  fi
}

# ── The realm role ───────────────────────────────────────────────────────────
ROLE_URL="${BASE}/roles/${ROLE_NAME}"
CODE=$(curl -sS -o /dev/null -w '%{http_code}' "${AUTH[@]}" "$ROLE_URL")
if [[ "$CODE" == "200" ]]; then
  code=$(jq -c '.role' "$CLIENTS_FILE" | curl -sS -o "$TMPD/out" -w '%{http_code}' -X PUT "${AUTH[@]}" \
    -H 'Content-Type: application/json' "$ROLE_URL" --data-binary @- || true)
  report "role ${ROLE_NAME}" 204 "$code" updated
elif [[ "$CODE" == "404" ]]; then
  code=$(jq -c '.role' "$CLIENTS_FILE" | curl -sS -o "$TMPD/out" -w '%{http_code}' -X POST "${AUTH[@]}" \
    -H 'Content-Type: application/json' "${BASE}/roles" --data-binary @- || true)
  report "role ${ROLE_NAME}" 201 "$code" created
else
  echo "unexpected HTTP ${CODE} reading role ${ROLE_NAME}" >&2
  exit 1
fi

# client_uuid <clientId>: Keycloak's internal id, empty when absent. Fails on
# more than one match, which would mean an earlier run went wrong.
client_uuid() {
  local code
  code=$(curl -sS -o "$TMPD/clients.json" -w '%{http_code}' "${AUTH[@]}" \
    --get --data-urlencode "clientId=$1" "${BASE}/clients" || true)
  [[ "$code" == "200" ]] || { echo "could not look up client $1 -> HTTP ${code}" >&2; exit 1; }
  local n
  n=$(jqr 'length' "$TMPD/clients.json")
  [[ "$n" -le 1 ]] || { echo "client $1 exists ${n} times in realm ${REALM}; resolve that by hand first" >&2; exit 1; }
  jqr -r '.[0].id // empty' "$TMPD/clients.json"
}

# upsert_client <clientId> <json>: create or update; prints nothing else.
upsert_client() {
  local cid="$1" json="$2" uuid code
  uuid=$(client_uuid "$cid")
  if [[ -n "$uuid" ]]; then
    code=$(jq -c --arg id "$uuid" '. + {id: $id}' <<<"$json" \
      | curl -sS -o "$TMPD/out" -w '%{http_code}' -X PUT "${AUTH[@]}" \
          -H 'Content-Type: application/json' "${BASE}/clients/${uuid}" --data-binary @- || true)
    report "client ${cid}" 204 "$code" updated
  else
    code=$(curl -sS -o "$TMPD/out" -w '%{http_code}' -X POST "${AUTH[@]}" \
      -H 'Content-Type: application/json' "${BASE}/clients" --data-binary @- <<<"$json" || true)
    report "client ${cid}" 201 "$code" created
  fi
}

# upsert_mappers <clientId>: the file's mappers on that client, by name.
upsert_mappers() {
  local cid="$1" uuid url code count i name id
  uuid=$(client_uuid "$cid")
  [[ -n "$uuid" ]] || { echo "client ${cid} absent after it was written" >&2; exit 1; }
  url="${BASE}/clients/${uuid}/protocol-mappers/models"
  code=$(curl -sS -o "$TMPD/mappers.json" -w '%{http_code}' "${AUTH[@]}" "$url" || true)
  [[ "$code" == "200" ]] || { echo "could not list the mappers of ${cid} -> HTTP ${code}" >&2; exit 1; }
  count=$(jqr '.mappers | length' "$CLIENTS_FILE")
  for ((i = 0; i < count; i++)); do
    name=$(jqr -r ".mappers[$i].name" "$CLIENTS_FILE")
    id=$(jqr -r --arg n "$name" '[.[] | select(.name == $n)][0].id // empty' "$TMPD/mappers.json")
    if [[ -n "$id" ]]; then
      code=$(jq -c --arg id "$id" ".mappers[$i] + {id: \$id}" "$CLIENTS_FILE" \
        | curl -sS -o "$TMPD/out" -w '%{http_code}' -X PUT "${AUTH[@]}" \
            -H 'Content-Type: application/json' "${url}/${id}" --data-binary @- || true)
      report "mapper ${name} on ${cid}" 204 "$code" updated
    else
      code=$(jq -c ".mappers[$i]" "$CLIENTS_FILE" \
        | curl -sS -o "$TMPD/out" -w '%{http_code}' -X POST "${AUTH[@]}" \
            -H 'Content-Type: application/json' "$url" --data-binary @- || true)
      report "mapper ${name} on ${cid}" 201 "$code" created
    fi
  done
}

# ── The public clients ───────────────────────────────────────────────────────
for ((i = 0; i < PUBLIC_COUNT; i++)); do
  cid=$(jqr -r ".publicClients[$i].clientId" "$CLIENTS_FILE")
  upsert_client "$cid" "$(public_client_json "$i")"
  upsert_mappers "$cid"
done

# ── The e2e client and user ──────────────────────────────────────────────────
if [[ "$WITH_E2E" == "true" ]]; then
  upsert_client "$E2E_CLIENT" "$(e2e_client_json)"
  upsert_mappers "$E2E_CLIENT"

  code=$(curl -sS -o "$TMPD/users.json" -w '%{http_code}' "${AUTH[@]}" \
    --get --data-urlencode "username=${E2E_USER}" --data-urlencode "exact=true" "${BASE}/users" || true)
  [[ "$code" == "200" ]] || { echo "could not look up user ${E2E_USER} -> HTTP ${code}" >&2; exit 1; }
  USER_ID=$(jqr -r '.[0].id // empty' "$TMPD/users.json")
  if [[ -n "$USER_ID" ]]; then
    code=$(e2e_user_json | curl -sS -o "$TMPD/out" -w '%{http_code}' -X PUT "${AUTH[@]}" \
      -H 'Content-Type: application/json' "${BASE}/users/${USER_ID}" --data-binary @- || true)
    report "user ${E2E_USER}" 204 "$code" updated
  else
    code=$(e2e_user_json | curl -sS -o "$TMPD/out" -w '%{http_code}' -X POST "${AUTH[@]}" \
      -H 'Content-Type: application/json' "${BASE}/users" --data-binary @- || true)
    report "user ${E2E_USER}" 201 "$code" created
    USER_ID=$(curl -sS "${AUTH[@]}" --get --data-urlencode "username=${E2E_USER}" \
      --data-urlencode "exact=true" "${BASE}/users" | jqr -r '.[0].id // empty')
    [[ -n "$USER_ID" ]] || { echo "user ${E2E_USER} absent after it was created" >&2; exit 1; }
  fi

  code=$(password_json | curl -sS -o "$TMPD/out" -w '%{http_code}' -X PUT "${AUTH[@]}" \
    -H 'Content-Type: application/json' "${BASE}/users/${USER_ID}/reset-password" --data-binary @- || true)
  report "password of ${E2E_USER}" 204 "$code" set

  HAS=$(curl -sS "${AUTH[@]}" "${BASE}/users/${USER_ID}/role-mappings/realm" \
    | jqr -r --arg r "$ROLE_NAME" '[.[].name] | index($r) // empty')
  if [[ -n "$HAS" ]]; then
    printf '  %-13s %s\n' present "${ROLE_NAME} on ${E2E_USER}"
  else
    code=$(curl -sS "${AUTH[@]}" "$ROLE_URL" | jq -c '[{id, name}]' \
      | curl -sS -o "$TMPD/out" -w '%{http_code}' -X POST "${AUTH[@]}" \
          -H 'Content-Type: application/json' "${BASE}/users/${USER_ID}/role-mappings/realm" --data-binary @- || true)
    report "${ROLE_NAME} on ${E2E_USER}" 204 "$code" granted
  fi
fi

# ── Verify, rather than trust the status codes ───────────────────────────────
# client_uuid already fails on a duplicate; this checks every client is there
# and carries each mapper exactly once.
CHECK=()
for ((i = 0; i < PUBLIC_COUNT; i++)); do CHECK+=("$(jqr -r ".publicClients[$i].clientId" "$CLIENTS_FILE")"); done
[[ "$WITH_E2E" == "true" ]] && CHECK+=("$E2E_CLIENT")
WANTED=$(jqr -r '.mappers[].name' "$CLIENTS_FILE" | sort)
for cid in "${CHECK[@]}"; do
  uuid=$(client_uuid "$cid")
  [[ -n "$uuid" ]] || { echo "client ${cid} absent after the run" >&2; exit 1; }
  HAVE=$(curl -sS "${AUTH[@]}" "${BASE}/clients/${uuid}/protocol-mappers/models" | jqr -r '.[].name' | sort)
  DUPES=$(uniq -d <<<"$HAVE")
  [[ -z "$DUPES" ]] || { echo "duplicate mappers on ${cid}: ${DUPES}" >&2; exit 1; }
  while IFS= read -r name; do
    grep -qxF -- "$name" <<<"$HAVE" || { echo "mapper ${name} absent on ${cid}" >&2; exit 1; }
  done <<<"$WANTED"
done
echo "→ verified: role ${ROLE_NAME}, clients ${CHECK[*]} in realm ${REALM}"

if [[ "$WITH_E2E" == "true" ]]; then
  uuid=$(client_uuid "$E2E_CLIENT")
  SECRET=$(curl -sS "${AUTH[@]}" "${BASE}/clients/${uuid}/client-secret" | jqr -r '.value // empty')
  [[ -n "$SECRET" ]] || { echo "could not read the ${E2E_CLIENT} client secret" >&2; exit 1; }
  echo "→ LDE_E2E_CLIENT_SECRET for the fixtures deploy (store it, do not commit it):"
  echo "  ${SECRET}"
fi
echo "Done."
